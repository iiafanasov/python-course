# Нарисуй на бумаге таблицу из двух столбцов: «roll» и «что напечатано».
# Заполни её для каждого числа от 1 до 6. Потом запусти программу несколько раз
# и проверь свою таблицу. Если что-то не совпало — допиши ниже комментарий: почему.
import random

roll = random.randint(1, 6)
print(f"Выпало: {roll}")
if roll >= 5 and roll != 6:
    print("Удача")
elif roll == 6 or roll == 1:
    print("Особый бросок")
else:
    print("Обычный ход")
